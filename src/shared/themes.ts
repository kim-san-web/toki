/**
 * TOKI theme library.
 *
 * Pure data + pure functions. No imports, no side effects — safe to load from
 * the main process, the preload bridge, and the renderer alike.
 *
 * Hard rules every palette in here obeys (see the verification notes at the
 * bottom of this file):
 *
 *  1. `surface` and `card` are rgba() strings with alpha >= 0.95. The notch is
 *     a transparent, always-on-top window on Windows where `backdrop-filter`
 *     does NOT blur the desktop behind it — a translucent panel is simply
 *     see-through and whatever is on the desktop bleeds through the UI. Alpha
 *     is the only thing providing legibility, so it stays near-opaque.
 *  2. `text` sits at >= 7:1 WCAG contrast against `surface`. Light themes have
 *     dark text on a light surface; dark themes the reverse.
 *  3. `ample` / `watch` / `critical` stay mutually distinguishable and readable
 *     against `surface` (>= 3:1), and read as calm -> warning -> urgent.
 *  4. `accent` is clearly visible against `surface` (>= 3:1).
 */

export interface ThemePalette {
  ink: string;          // deepest background
  surface: string;      // notch panel bg — MUST be rgba with alpha >= 0.95
  surfaceSolid: string; // opaque settings-window bg (hex)
  card: string;         // detail card bg — rgba, alpha >= 0.95
  hairline: string;     // subtle border, rgba
  hairlineStrong: string;
  text: string;         // primary text
  muted: string;        // secondary text
  faint: string;        // tertiary text
  accent: string;       // brand/interactive accent
  grey: string;         // the logo's dimmed arc colour
  track: string;        // unfilled ring/bar track
  ample: string;        // usage band < 50%
  watch: string;        // 50–70%
  critical: string;     // > 70%
}

export type ThemeMood = 'dark' | 'light';

export type ThemeGroup = 'essential' | 'nature' | 'vivid' | 'soft' | 'retro' | 'pro';

export type ThemeMotif = 'none' | 'petals' | 'stars' | 'circuit' | 'waves' | 'grid' | 'sparkle';

export interface Theme {
  id: string;           // kebab-case, unique
  name: string;         // short display name
  blurb: string;        // ONE short sentence describing the vibe, max 60 chars
  group: ThemeGroup;
  mood: ThemeMood;
  palette: ThemePalette;
  /** Optional decorative motif drawn faintly in the notch. */
  motif?: ThemeMotif;
}

