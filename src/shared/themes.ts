export const DEFAULT_THEME_ID = 'toki-dark';

/** Look up a theme by id. Returns null rather than throwing so callers can fall back. */
export function themeById(id: string): Theme | null {
  for (const theme of THEMES) {
    if (theme.id === id) return theme;
  }
  return null;
}

/** All themes belonging to a group, in declaration order. */
export function themesByGroup(group: ThemeGroup): Theme[] {
  return THEMES.filter((theme) => theme.group === group);
}

/** Maps a palette to the CSS custom properties the app already uses. */
export function paletteToCssVars(p: ThemePalette): Record<string, string> {
  return {
    '--toki-ink': p.ink,
    '--toki-surface': p.surface,
    '--toki-surface-solid': p.surfaceSolid,
    '--toki-card': p.card,
    '--toki-hairline': p.hairline,
    '--toki-hairline-strong': p.hairlineStrong,
    '--toki-text': p.text,
    '--toki-muted': p.muted,
    '--toki-faint': p.faint,
    '--toki-accent': p.accent,
    '--toki-grey': p.grey,
    '--track': p.track,
    '--band-ample': p.ample,
    '--band-watch': p.watch,
    '--band-critical': p.critical,
  };
}
